import assert from 'node:assert/strict';
import {arrangeLayout,dropDocument,emptyLayout,reconcileLayout} from '../src/document-layout.ts';
let layout=reconcileLayout(emptyLayout(),[1,2,3,4],1);
layout=dropDocument(layout,2,0,'right');
assert.equal(layout.columns,2);assert.deepEqual(layout.panes.map(p=>p.tabs),[[1,3,4],[2]]);
layout=dropDocument(layout,3,1,'left');
assert.equal(layout.columns,3);assert.deepEqual(layout.panes.map(p=>p.tabs),[[1,4],[3],[2]]);
layout=dropDocument(layout,4,1,'bottom');
assert.equal(layout.rows,2);assert.equal(layout.panes[4].selected,4);
layout=dropDocument(layout,1,4,'top');
assert.equal(layout.rows,3);assert.equal(layout.columns,3);
const ids=p=>p.panes.flatMap(p=>p.tabs).sort();
assert.deepEqual(ids(layout),[1,2,3,4]);
layout=dropDocument(layout,2,8,'center');assert.equal(layout.panes[8].selected,2);
layout=dropDocument(layout,3,8,'right');assert.equal(layout.columns,3);assert.deepEqual(ids(layout),[1,2,3,4]);
layout=reconcileLayout(layout,[1,2,4],2);assert.deepEqual(ids(layout),[1,2,4]);assert.equal(layout.panes[8].selected,2);
layout=reconcileLayout(layout,[1,2,4,5],5);assert.deepEqual(ids(layout),[1,2,4,5]);
layout=arrangeLayout(layout,1,1);assert.deepEqual(ids(layout),[1,2,4,5]);assert.equal(layout.panes.length,1);
for(const [r,c] of [[1,2],[1,3],[2,1],[3,1],[2,2],[3,3]]){const arranged=arrangeLayout(layout,r,c);assert.equal(arranged.panes.length,r*c);assert.deepEqual(ids(arranged),[1,2,4,5]);}
assert.deepEqual(dropDocument(layout,999,0,'left'),layout);assert.deepEqual(dropDocument(layout,1,99,'left'),layout);
assert.deepEqual(arrangeLayout(layout,99,1),layout);
assert.deepEqual(reconcileLayout(layout,[],null),emptyLayout());
// New documents join the focused group once all panes are occupied.
layout=reconcileLayout(arrangeLayout(reconcileLayout(emptyLayout(),[1,2],1),1,2),[1,2],2);
layout=reconcileLayout(layout,[1,2,3],3);assert.deepEqual(layout.panes[1].tabs,[2,3]);
console.log('Document layout: split, move, close, focus, consolidate, all presets passed.');
const {resizeLayout}=await import('../src/document-layout.ts');
let weighted=arrangeLayout(layout,2,3);
weighted=resizeLayout(weighted,'columns',0,.12,.1);
assert.ok(Math.abs(weighted.columnSizes[0]-(1/3+.12))<1e-9);assert.equal(weighted.columnSizes[2],1/3);
assert.ok(Math.abs(weighted.columnSizes.reduce((a,b)=>a+b,0)-1)<1e-9);
weighted=resizeLayout(weighted,'columns',0,100,.1);assert.ok(weighted.columnSizes[1]>=.1-1e-9);
weighted=resizeLayout(weighted,'rows',0,-100,.15);assert.equal(weighted.rowSizes[0],.15);
assert.deepEqual(ids(weighted),ids(layout));
assert.equal(resizeLayout(weighted,'rows',9,0,.1),weighted);
assert.equal(resizeLayout(weighted,'rows',0,NaN,.1),weighted);
weighted=dropDocument(reconcileLayout(emptyLayout(),[1,2],1),2,0,'right');
assert.deepEqual(weighted.columnSizes,[.5,.5]);
console.log('Pane resize: pair conservation, minimum sizes, split weights, invalid edits passed.');
